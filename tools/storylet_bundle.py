"""Bundle approved and draft storylets for the browser: writes web/storylets_data.js (var STORYLET_DATA = {...}).
Rejected storylets are left out. Deterministic (no timestamps) so the file diffs cleanly. Run after every review pass:
  python3 -I tools/storylet_bundle.py [--approved-only]
Runtime: Storylets.fromBundle(STORYLET_DATA, {seed}).  In Node: JSON.parse of the same object via require('../web/storylets_data.js')."""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import storylet_lib as L

W = L.World()
keep = ('approved',) if '--approved-only' in sys.argv else ('approved', 'draft')
sl = [s for _, s in L.load_storylets(statuses=keep)]
defaults = {k: v.get('default') for k, v in W.vars.items() if 'default' in v}
defs = {k: {x: v[x] for x in ('type', 'min', 'max', 'oneway', 'values', 'derived') if x in v} for k, v in W.vars.items()}
data = {'storylets': sl, 'defaults': defaults, 'defs': defs, 'count': len(sl)}
out = os.path.join(L.ROOT, 'web', 'storylets_data.js')
with open(out, 'w', encoding='utf-8') as f:
    f.write('/* GENERATED by tools/storylet_bundle.py from data/narrative/storylets/*.json. Do not edit. */\n')
    f.write('var STORYLET_DATA = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':'), sort_keys=True) + ';\n')
    f.write("if (typeof module !== 'undefined') module.exports = STORYLET_DATA;\n")
print('wrote %s: %d storylets (%s)' % (os.path.relpath(out, L.ROOT), len(sl), '/'.join(keep)))
